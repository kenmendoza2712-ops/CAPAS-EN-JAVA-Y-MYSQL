    private void BtnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEliminarActionPerformed
     
       int e = JOptionPane.showConfirmDialog(null, "Desea Eliminar a "+TxtNombre.getText()+" "+TxtApellido1.getText() ,"Eliminar", JOptionPane.YES_NO_CANCEL_OPTION);
        if (e ==0) {
            Alg.Eliminar(TxtCedula.getText());
            showTable();
            cleanWin();
            JOptionPane.showMessageDialog(null, "Dato eliminado");
        }
        
    }//GEN-LAST:event_BtnEliminarActionPerformed

    private void TblAlumnoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TblAlumnoMouseClicked
       
        int i = TblAlumno.getSelectedRow();
        TxtCedula.setText(TblAlumno.getValueAt(i, 0).toString());
        TxtNombre.setText(TblAlumno.getValueAt(i, 1).toString());
        TxtApellido1.setText(TblAlumno.getValueAt(i, 2).toString());
        TxtApellido2.setText(TblAlumno.getValueAt(i, 3).toString());
        TxtFechaN.setText(TblAlumno.getValueAt(i, 4).toString());
        TxtCorreo.setText(TblAlumno.getValueAt(i, 5).toString());
        TxtCarnet.setText(TblAlumno.getValueAt(i, 6).toString());
        TxtCedula.setEnabled(false);
        BtnGuardar.setEnabled(false);
        
    }//GEN-LAST:event_TblAlumnoMouseClicked

